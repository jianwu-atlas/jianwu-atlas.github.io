#!/usr/bin/env python3
"""Add loading="lazy" + decoding="async" to every <img> tag in the site's
static HTML pages, except the above-the-fold images that must stay eager.

Exempt (kept eager on purpose - they are Largest-Contentful-Paint candidates
and lazy-loading them would *hurt* performance):
  - class contains "brand-icon-img"  (navbar brand logo)
  - class contains "hero-logo-img"  (homepage hero lockup)
  - images inside .profile-pic       (homepage avatar)
  - class contains "soc-icon-img"   (social icon row, hero area)

Idempotent: tags that already carry a loading attribute are left untouched.
Run from anywhere; paths are resolved relative to the repository root.
"""
from __future__ import annotations

import re
import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parent.parent
SKIP_DIRS = {".git", ".wrangler", "private-notes", "__pycache__"}

# Files we must NOT touch directly:
#  - assets/pdfjs: vendored pdf.js viewer, its own markup
#  - tutorials/: generated by scripts/build_tutorials.py from
#    assets/templates/tutorial_template.html -- patch the template and
#    re-run the build instead, otherwise the next build overwrites it.
SKIP_PATHS = {
    Path("assets/pdfjs"),
    Path("tutorials"),
}

EAGER_MARKERS = ("brand-icon-img", "hero-logo-img", "soc-icon-img")
EAGER_PARENT_CLASS = ("profile-pic",)

IMG_TAG_RE = re.compile(r"<img\b[^>]*>", re.IGNORECASE)
HAS_LOADING_RE = re.compile(r"""\bloading\s*=""", re.IGNORECASE)


def iter_html_files(root: Path):
    for path in sorted(root.rglob("*.html")):
        rel = path.relative_to(root)
        if any(part in SKIP_DIRS for part in rel.parts):
            continue
        # Compare path *parts*, not string prefixes, so that the root-level
        # file "tutorials.html" is not mistaken for the "tutorials/" directory.
        if any(rel.parts[:len(skip.parts)] == skip.parts for skip in SKIP_PATHS):
            continue
        yield path


def is_eager(tag: str) -> bool:
    for marker in EAGER_MARKERS:
        if marker in tag:
            return True
    for cls in EAGER_PARENT_CLASS:
        if cls in tag:
            return True
    # <img src="assets/img/avatar.jpg"> style avatar without a wrapper class
    if re.search(r'src="[^"]*avatar\.jpg"', tag, re.IGNORECASE):
        return True
    return False


def patch_html(text: str) -> tuple[str, int]:
    changed = 0

    def repl(m: re.Match) -> str:
        nonlocal changed
        tag = m.group(0)
        if HAS_LOADING_RE.search(tag):
            return tag
        if is_eager(tag):
            return tag
        changed += 1
        return tag[:-1].rstrip() + ' loading="lazy" decoding="async">'

    return IMG_TAG_RE.sub(repl, text), changed


def main() -> int:
    total_tags = 0
    total_files = 0
    for path in iter_html_files(REPO_ROOT):
        original = path.read_text(encoding="utf-8")
        patched, n = patch_html(original)
        if n:
            path.write_text(patched, encoding="utf-8")
            total_tags += n
            total_files += 1
            print(f"[ok] {path.relative_to(REPO_ROOT)}: {n} img tag(s)")

    print(f"\nDone. {total_tags} img tag(s) across {total_files} file(s) "
          f"now use lazy loading.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
